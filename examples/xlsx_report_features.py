"""A combined XLSX report: formulas, validation, hyperlinks, a logo, print setup, charts.

Usage:
    python examples/xlsx_report_features.py [--logo company_logo.png] [--out report.xlsx]

``--logo`` takes a PNG or JPEG file; it is embedded unchanged.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "../src")))

from xlspy import (  # noqa: E402
    Chart,
    ChartAxis,
    ChartLegend,
    ChartMarker,
    ChartSeries,
    DataLabels,
    DataValidation,
    ExcelTable,
    Formula,
    Hyperlink,
    Image,
    PageMargins,
    PrintSettings,
    Style,
    XlsxWriter,
)


def build_report(path, logo=None):
    header = ["Product", "Units", "Unit price", "Revenue", "Status", "Details"]
    rows = [header]
    products = [("Coffee", 120, 12.5), ("Tea", 80, 8.4), ("Cocoa", 45, 15.0), ("Water", 300, 1.2)]
    for index, (name, units, price) in enumerate(products, start=2):
        rows.append([
            name,
            units,
            price,
            Formula(f"B{index}*C{index}"),          # formulas stay formulas
            "Active",
            Hyperlink(f"https://example.com/products/{name.lower()}", text="Product page"),
        ])
    total_row = len(rows) + 1
    rows.append(["Total", Formula(f"SUM(B2:B{total_row - 1})"), None,
                 Formula(f"SUM(D2:D{total_row - 1})"), None, None])

    images = [Image(logo, anchor="H1", width=180, description="Company logo")] if logo else None

    with XlsxWriter(path) as writer:
        writer.add_sheet("Summary")
        writer.write_sheet(
            rows,
            header_style=Style(bold=True, fill="#183C52", font_color="#FFFFFF"),
            styles={
                f"C2:C5": Style(number_format="#,##0.00"),
                f"D2:D{total_row}": Style(number_format="#,##0.00"),
            },
            tables=[ExcelTable("ProductSales", f"A1:F{total_row - 1}")],
            data_validations=[
                # Dropdown with a literal list; invalid entries are refused.
                DataValidation(
                    "list", f"E2:E{total_row - 1}", formula1='"Active,Paused,Closed"',
                    show_input_message=True, prompt_title="Status", prompt="Pick a status",
                    error_title="Unknown status", error="Choose Active, Paused or Closed.",
                ),
                # Whole numbers only, with a range check.
                DataValidation("whole", f"B2:B{total_row - 1}", formula1=0, formula2=10000,
                               error="Units must be between 0 and 10000."),
            ],
            images=images,
            print_settings=PrintSettings(
                orientation="landscape", paper_size="A4", print_area=f"A1:F{total_row}",
                repeat_rows="1:1", fit_to_width=1, fit_to_height=0, center_horizontally=True,
                header="&LSales report&RPage &P of &N", footer="&CGenerated by xlspy",
                margins=PageMargins(left=0.5, right=0.5),
            ),
            charts=[
                Chart(
                    "barh",
                    [ChartSeries(f"D2:D5", categories="A2:A5", title="Revenue", color="#2E75B6")],
                    title="Revenue by product", anchor="H12",
                    x_axis=ChartAxis(reverse=True),
                    y_axis=ChartAxis(title="Revenue", minimum=0, number_format="#,##0"),
                    data_labels=DataLabels(number_format="#,##0", position="outside_end"),
                    legend=False,
                ),
                Chart(
                    "scatter",
                    [ChartSeries("D2:D5", x_values="B2:B5", title="Revenue vs units",
                                 color="#C00000", marker=ChartMarker("circle", 8))],
                    title="Units against revenue", anchor="H32",
                    x_axis=ChartAxis(title="Units sold", minimum=0),
                    y_axis=ChartAxis(title="Revenue", number_format="#,##0"),
                    legend=ChartLegend("bottom"),
                ),
            ],
        )
    return path


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--logo", help="PNG or JPEG logo to place at H1")
    parser.add_argument("--out", default="report_features.xlsx", help="output workbook")
    args = parser.parse_args()
    path = build_report(args.out, logo=args.logo)
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
