@pytest.mark.parametrize("facade", sorted(FACADE_NAMES))
def test_facade_still_exports_every_name(facade):
    module = importlib.import_module(facade)
    missing = [name for name in FACADE_NAMES[facade] if not hasattr(module, name)]
    assert missing == []


@pytest.mark.parametrize("facade", sorted(FACADE_NAMES))
def test_facade_names_are_the_defining_modules_objects(facade):
    module = importlib.import_module(facade)
    for name in FACADE_NAMES[facade]:
        obj = getattr(module, name)
        if inspect.isclass(obj) or inspect.isfunction(obj):
            defining = importlib.import_module(obj.__module__)
            assert getattr(defining, obj.__name__) is obj, f"{facade}.{name}"
