NS = {
    "m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main",
    "r": "http://schemas.openxmlformats.org/officeDocument/2006/relationships",
    "pkg": "http://schemas.openxmlformats.org/package/2006/relationships",
    "ct": "http://schemas.openxmlformats.org/package/2006/content-types",
    "xdr": "http://schemas.openxmlformats.org/drawingml/2006/spreadsheetDrawing",
}

# CT_Worksheet child order (ECMA-376 Part 1, 18.3.1.99); only the names used here.
WORKSHEET_ORDER = [
    "sheetPr", "dimension", "sheetViews", "sheetFormatPr", "cols", "sheetData",
    "sheetCalcPr", "sheetProtection", "protectedRanges", "scenarios", "autoFilter",
    "sortState", "dataConsolidate", "customSheetViews", "mergeCells", "phoneticPr",
    "conditionalFormatting", "dataValidations", "hyperlinks", "printOptions",
    "pageMargins", "pageSetup", "headerFooter", "rowBreaks", "colBreaks",
    "customProperties", "cellWatches", "ignoredErrors", "smartTags", "drawing",
    "legacyDrawing", "legacyDrawingHF", "picture", "oleObjects", "controls",
    "webPublishItems", "tableParts", "extLst",
]


def _png(path, width=4, height=4):
    raw = b"".join(b"\x00" + b"\xff\x00\x00" * width for _ in range(height))

    def chunk(kind, data):
        body = kind + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF)

    header = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    path.write_bytes(
        b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header)
        + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b"")
    )
    return path


def _report_rows():
    summary = [
        ["Quarterly report", None, None, None, None, None],
        ["Product", "Units", "Unit price", "Revenue", "Status", "Details"],
    ]
    products = [("Coffee", 120, 12.5), ("Tea", 80, 8.4), ("Cocoa", 45, 15.0), ("Water", 300, 1.2)]
    for index, (name, units, price) in enumerate(products, start=3):
        summary.append([
            name, units, price, Formula(f"B{index}*C{index}"), "Active",
            Hyperlink(f"https://example.com/{name.lower()}", text="Product page"),
        ])
    summary.append(["Total", Formula("SUM(B3:B6)"), None, Formula("SUM(D3:D6)"), None, None])
    summary.append([])
    summary.append(["Q1 total", Formula("SUM('Q1 Sales'!B2:B4)")])
    summary.append(["First date", Formula("Data!A2")])
    q1 = [["Month", "Sales"], ["Jan", 10], ["Feb", 12], ["Mar", 9]]
    data = [["Date", "Value"]]
    start = datetime.date(2026, 1, 1)
    for offset in range(3):
        data.append([start + datetime.timedelta(days=offset * 31), offset * 1.5])
    return summary, q1, data


def build_report(path, logo):
    summary, q1, data = _report_rows()
    with XlsxWriter(path) as writer:
        writer.add_sheet("Summary")
        writer.write_sheet(
            summary,
            header_style=Style(bold=True, fill="#183C52", font_color="#FFFFFF"),
            styles={"C3:C6": Style(number_format="#,##0.00"), "D3:D7": Style(number_format="#,##0.00")},
            merges=["A1:F1"],
            column_widths={"A": 22, "B": 12, "F": 24},
            freeze_panes="A3",
            tables=[ExcelTable("ProductSales", "A2:F6")],
            conditional_formats=[CellIsRule("D3:D6", "greaterThan", ["100"])],
            data_validations=[
                DataValidation("list", "E3:E6", formula1='"Active,Paused,Closed"',
                               error="Choose Active, Paused or Closed."),
                DataValidation("whole", "B3:B6", formula1=0, formula2=10000,
                               error="Units must be between 0 and 10000."),
            ],
            images=[Image(logo, anchor="H1", width=120, description="Company logo")],
            print_settings=PrintSettings(
                orientation="landscape", paper_size="A4", print_area="A1:F7",
                repeat_rows="2:2", fit_to_width=1, fit_to_height=0, center_horizontally=True,
                header="&LQuarterly report&RPage &P of &N", footer="&CGenerated by xlspy",
                margins=PageMargins(left=0.5, right=0.5),
            ),
            charts=[
                Chart("bar", [ChartSeries("D3:D6", categories="A3:A6", title="Revenue")],
                      title="Revenue by product", anchor="H3",
                      y_axis=ChartAxis(title="Revenue", minimum=0, number_format="#,##0"),
                      data_labels=DataLabels(number_format="#,##0", position="outside_end"),
                      legend=False),
                Chart("barh", [ChartSeries("B3:B6", categories="A3:A6", title="Units")],
                      title="Units by product", anchor="H21",
                      x_axis=ChartAxis(reverse=True), legend=ChartLegend("bottom")),
                Chart("scatter", [ChartSeries("D3:D6", x_values="B3:B6", title="Revenue vs units",
                                              color="#C00000", marker=ChartMarker("circle", 8))],
                      title="Units against revenue", anchor="H39",
                      x_axis=ChartAxis(title="Units sold", minimum=0),
                      y_axis=ChartAxis(title="Revenue"), legend=ChartLegend("bottom")),
            ],
        )
        writer.add_sheet("Q1 Sales")
        writer.write_sheet(q1, header_style=Style(bold=True), auto_filter=True)
        writer.add_sheet("Data")
        writer.write_sheet(data, styles={"A2:A4": Style(number_format="yyyy-mm-dd")})
    return path


def _package(path):
    """Parse every XML part and return (name -> ElementTree root) plus raw names."""
    roots = {}
    with zipfile.ZipFile(path) as archive:
        names = archive.namelist()
        for name in names:
            if name.endswith((".xml", ".rels")):
                roots[name] = ElementTree.fromstring(archive.read(name))
    return roots, names


def _local(tag):
    return tag.rsplit("}", 1)[-1]


def _rel_ids(root):
    ids = [rel.get("Id") for rel in root.findall("pkg:Relationship", NS)]
    return ids


