def test_report_reads_back_every_feature_in_openpyxl(tmp_path):
    logo = _png(tmp_path / "logo.png")
    path = build_report(tmp_path / "report.xlsx", logo)
    wb = openpyxl.load_workbook(path)

    assert wb.sheetnames == ["Summary", "Q1 Sales", "Data"]
    ws = wb["Summary"]
    assert ws["A1"].value == "Quarterly report"
    assert "A1:F1" in [str(r) for r in ws.merged_cells.ranges]
    assert ws.freeze_panes == "A3"
    assert ws.column_dimensions["A"].width == pytest.approx(22.0)
    assert "ProductSales" in ws.tables
    assert ws["D3"].value == "=B3*C3"
    assert ws["B8"].value is None and ws["B9"].value == "=SUM('Q1 Sales'!B2:B4)"
    assert ws["B10"].value == "=Data!A2"
    assert ws["F3"].hyperlink.target == "https://example.com/coffee"
    assert len(ws.data_validations.dataValidation) == 2
    assert ws.conditional_formatting, "conditional formatting was dropped"
    assert ws.print_title_rows == "$2:$2"
    assert ws.page_setup.orientation == "landscape"
    assert ws.page_setup.paperSize == 9                    # A4 (ECMA-376 paperSize code)
    if importlib.util.find_spec("PIL") is not None:
        assert len(ws._images) == 1  # openpyxl loads pictures only when Pillow is installed
    assert len(ws._charts) == 3
    assert wb["Q1 Sales"].auto_filter.ref == "A1:B4"


