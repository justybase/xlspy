def test_every_xml_part_parses_and_content_types_cover_every_part(tmp_path):
    logo = _png(tmp_path / "logo.png")
    path = build_report(tmp_path / "report.xlsx", logo)
    roots, names = _package(path)

    overrides = {o.get("PartName") for o in roots["[Content_Types].xml"].findall("ct:Override", NS)}
    defaults = {d.get("Extension") for d in roots["[Content_Types].xml"].findall("ct:Default", NS)}
    for name in names:
        if name == "[Content_Types].xml" or name.endswith("/"):
            continue
        part = "/" + name
        extension = name.rsplit(".", 1)[-1]
        assert part in overrides or extension in defaults, f"no content type for {name}"


def test_relationship_ids_are_unique_and_every_reference_resolves(tmp_path):
    logo = _png(tmp_path / "logo.png")
    path = build_report(tmp_path / "report.xlsx", logo)
    roots, names = _package(path)

    for name in names:
        if not name.endswith(".rels"):
            continue
        ids = _rel_ids(roots[name])
        assert len(ids) == len(set(ids)), f"duplicate relationship ids in {name}"

    for name in names:
        if not name.startswith("xl/worksheets/sheet") or name.endswith(".rels"):
            continue
        rels_name = name.replace("worksheets/", "worksheets/_rels/") + ".rels"
        declared = set(_rel_ids(roots[rels_name])) if rels_name in roots else set()
        for element in roots[name].iter():
            for attr, value in element.attrib.items():
                if attr.startswith("{%s}" % NS["r"]):
                    assert value in declared, f"{name} references missing relationship {value}"


def test_worksheet_children_follow_schema_order(tmp_path):
    logo = _png(tmp_path / "logo.png")
    path = build_report(tmp_path / "report.xlsx", logo)
    roots, names = _package(path)

    for name in names:
        if not re.fullmatch(r"xl/worksheets/sheet\d+\.xml", name):
            continue
        order = [WORKSHEET_ORDER.index(_local(child.tag)) for child in roots[name]
                 if _local(child.tag) in WORKSHEET_ORDER]
        assert order == sorted(order), f"out-of-order worksheet children in {name}"
        assert {_local(c.tag) for c in roots[name]} <= set(WORKSHEET_ORDER)


def test_drawing_object_ids_and_chart_references_are_consistent(tmp_path):
    logo = _png(tmp_path / "logo.png")
    path = build_report(tmp_path / "report.xlsx", logo)
    roots, names = _package(path)

    drawings = [n for n in names if re.fullmatch(r"xl/drawings/drawing\d+\.xml", n)]
    assert len(drawings) == 1
    drawing = roots[drawings[0]]
    ids = [int(node.get("id")) for node in drawing.iter("{%s}cNvPr" % NS["xdr"])]
    assert len(ids) == len(set(ids)), "duplicate drawing object ids"
    anchors = list(drawing)
    assert len(anchors) == 4                               # three charts and one picture

    chart_parts = sorted(n for n in names if re.fullmatch(r"xl/charts/chart\d+\.xml", n))
    assert len(chart_parts) == 3
    for chart in chart_parts:
        text = ElementTree.tostring(roots[chart], encoding="unicode")
        refs = re.findall(r"<c:f>([^<]+)</c:f>", text)
        assert refs, f"{chart} has no cell references"
        for ref in refs:
            assert "!" in ref and "=" not in ref, ref

    media = [n for n in names if n.startswith("xl/media/")]
    assert len(media) == 1


def test_formulas_are_serialized_without_leading_equals(tmp_path):
    logo = _png(tmp_path / "logo.png")
    path = build_report(tmp_path / "report.xlsx", logo)
    roots, names = _package(path)

    formulas = []
    for name in names:
        if re.fullmatch(r"xl/worksheets/sheet\d+\.xml", name):
            formulas += [f.text for f in roots[name].iter("{%s}f" % NS["m"])]
    assert formulas, "no formulas were written"
    assert all(text and not text.startswith("=") for text in formulas)
    assert "SUM('Q1 Sales'!B2:B4)" in formulas


def test_defined_names_cover_print_area_titles_and_filter(tmp_path):
    logo = _png(tmp_path / "logo.png")
    path = build_report(tmp_path / "report.xlsx", logo)
    roots, _ = _package(path)

    names_xml = {
        (d.get("name"), d.get("localSheetId")): d.text.replace("'", "")
        for d in roots["xl/workbook.xml"].iter("{%s}definedName" % NS["m"])
    }
    assert names_xml[("_xlnm.Print_Area", "0")] == "Summary!$A$1:$F$7"
    assert names_xml[("_xlnm.Print_Titles", "0")] == "Summary!$2:$2"
    assert names_xml[("_xlnm._FilterDatabase", "1")] == "Q1 Sales!$A$1:$B$4"


